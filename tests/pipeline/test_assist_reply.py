"""対話アシストの応答文(純関数)のテスト。

LLMの返事は「変更しました」と言いがちだが、実際は承認待ちで何も変わっていない。
応答文はLLMの言葉ではなく、機械側が把握している状態から作る。
"""

import pytest

from backend.pipeline.assist_reply import claims_change, compose_assist_reply


@pytest.mark.parametrize(
    ("llm_reply", "proposals", "rejected", "expected"),
    [
        # 案が1件: 何をどう変える案か+承認すると反映される
        (
            "反動体を半導体に変更しました。",
            [("反動体", "反動体(半導体)")],
            [],
            "「反動体」を「反動体(半導体)」に変える案を作りました。"
            "まだ反映していません。「承認」を押すと反映されます。",
        ),
        (
            "直しました",
            [("それ", "それ(ハッカソン)"), ("あれ", "あれ(イベント)")],
            [],
            "修正案を2件作りました。まだ反映していません。「承認」を押すと反映されます。",
        ),
        # 案が安全確認で全部落ちた: 変わっていないことと、直接直す方法を伝える
        (
            "消しておきました。",
            [],
            ["指示語の削除のみ(参照先の明示がない)"],
            "AIの修正案は安全のため採用しませんでした"
            "(理由: 指示語の削除のみ(参照先の明示がない))。この行は変わっていません。"
            "文字を直接直すときは、行の鉛筆ボタンを押してください。",
        ),
        # 案なし・ただの回答: 回答を見せたうえで、変えていないことを添える
        (
            "この『それ』はハッカソンを指していると思われます。",
            [],
            [],
            "この行は変わっていません。AIの回答: この『それ』はハッカソンを指していると思われます。",
        ),
        # 案なしなのに「変更しました」と言う: 誤解を招くので回答を出さない
        (
            "半導体に修正しました。",
            [],
            [],
            "この行は変わっていません。"
            "文字を直接直すときは、行の鉛筆ボタンを押してください。",
        ),
        ("", [], [], "この行は変わっていません。"),
    ],
    ids=["1件", "複数件", "安全確認で全部落ちた", "回答のみ", "変えたと言うが案なし", "返事なし"],
)
def test_compose_assist_reply(llm_reply, proposals, rejected, expected):
    assert compose_assist_reply(llm_reply, proposals, rejected) == expected


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("変更しました", True),
        ("半導体に修正しました。", True),
        ("置換しておきました", True),
        ("直しました", True),
        ("反映しました", True),
        ("書き換えました", True),
        ("「それ」はハッカソンのことです", False),
        ("修正案を提案します", False),
    ],
)
def test_claims_change(text, expected):
    assert claims_change(text) is expected
